export function getCity(id: string): City | undefined {
  return CITIES.find((c) => c.id === id);
}

export function requireCity(id: string): City {
  const city = getCity(id);
  if (!city) throw new Error(`Unknown city: ${id}`);
  return city;
}

/** Difficulty fallback order when a city has no zone for the requested level. */
export const DIFFICULTY_FALLBACK: Record<Difficulty, Difficulty[]> = {
  easy: ['easy', 'normal', 'hard', 'expert'],
  normal: ['normal', 'easy', 'hard', 'expert'],
  hard: ['hard', 'normal', 'expert', 'easy'],
  expert: ['expert', 'hard', 'normal', 'easy'],
};

export function zonesForDifficulty(city: City, difficulty: Difficulty): CityZone[] {
  for (const level of DIFFICULTY_FALLBACK[difficulty]) {
    const zones = city.zones.filter((zone) => zone.difficulty === level);
    if (zones.length > 0) return zones;
  }
  return city.zones;
}
