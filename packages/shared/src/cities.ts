import type { Difficulty, LatLng } from './types.js';

/**
 * A zone is a disc inside a city from which round locations are sampled.
 * Adding a city = adding an entry to CITIES. No engine change required.
 */
export interface CityZone {
  name: string;
  center: LatLng;
  radiusMeters: number;
  difficulty: Difficulty;
}

export interface City {
  id: string;
  name: string;
  country: string;
  countryCode: string;
  flag: string;
  center: LatLng;
  /** Initial viewport of the guess map: [south, west, north, east]. */
  bounds: [number, number, number, number];
  /** Sanity limit: a resolved panorama further than this from the center is rejected. */
  maxRadiusMeters: number;
  /** Scoring decay scale, bigger cities are more forgiving. */
  scoreScaleMeters: number;
  zones: CityZone[];
}

const z = (name: string, lat: number, lng: number, radiusMeters: number, difficulty: Difficulty): CityZone => ({
  name,
  center: { lat, lng },
  radiusMeters,
  difficulty,
});

